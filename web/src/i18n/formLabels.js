function build() {
  const out = { en: {}, ar: {}, fr: {} };
  const add = (key, en, ar, fr) => {
    out.en[key] = en;
    out.ar[key] = ar;
    out.fr[key] = fr;
  };
  COMMON.forEach((row) => add(...row));
  for (const [kind, rows] of [KITCHEN, BAR, OPENING, CLOSING, QC, AREA, OPS]) {
    rows.forEach(([path, en, ar, fr]) => add(`f.${kind}.${path}`, en, ar, fr));
  }
  return out;
}

export const FORM_LABELS = build();

// Title of a pinned report by its kind, falling back to the stored name
// (the template row keeps the English name it was created with).
export function reportTitle(t, kind, storedName) {
  const key = `f.${kind}.title`;
  return kind && FORM_LABELS.en[key] ? t(key) : storedName;
}
